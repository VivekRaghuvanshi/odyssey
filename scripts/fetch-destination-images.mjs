// One-time content-population script: downloads a real photo for every
// destination gallery image from Pexels (free API, no attribution
// required) and writes src/data/destination-images.generated.ts mapping
// each [destination slug, image id] to its local file + photographer
// credit. Run manually (`npm run fetch:images`) when adding/changing
// destinations — this is NOT wired into postinstall, since it needs a
// network call + API key and the downloaded files are committed to git.
import { mkdirSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = join(__dirname, "..");

const apiKey = process.env.PEXELS_API_KEY;
if (!apiKey) {
  console.error("PEXELS_API_KEY is not set. Run with --env-file=.env.local");
  process.exit(1);
}

const { destinations } = await import(
  pathToFileURL(join(rootDir, "src", "data", "destinations.ts")).href
);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function searchPhoto(query, orientation) {
  const url = new URL("https://api.pexels.com/v1/search");
  url.searchParams.set("query", query);
  url.searchParams.set("per_page", "1");
  url.searchParams.set("orientation", orientation);

  const res = await fetch(url, { headers: { Authorization: apiKey } });
  if (!res.ok) throw new Error(`Pexels search failed (${res.status}): ${query}`);
  const data = await res.json();
  if (data.photos?.length) return data.photos[0];

  // retry without the orientation constraint
  url.searchParams.delete("orientation");
  const res2 = await fetch(url, { headers: { Authorization: apiKey } });
  if (!res2.ok) throw new Error(`Pexels search retry failed (${res2.status}): ${query}`);
  const data2 = await res2.json();
  return data2.photos?.[0] ?? null;
}

async function downloadTo(url, filePath) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Download failed (${res.status}): ${url}`);
  const buffer = Buffer.from(await res.arrayBuffer());
  writeFileSync(filePath, buffer);
}

const manifest = {};

for (const destination of destinations) {
  manifest[destination.slug] = {};
  const destDir = join(rootDir, "public", "images", "destinations", destination.slug);
  if (!existsSync(destDir)) mkdirSync(destDir, { recursive: true });

  for (const image of destination.gallery) {
    const query = `${image.caption}, ${destination.country}`;
    process.stdout.write(`[fetch-images] ${destination.slug}/${image.id}: "${query}" … `);

    const photo = await searchPhoto(query, image.aspect === "square" ? "square" : image.aspect);
    if (!photo) {
      console.log("NO RESULT — skipped");
      continue;
    }

    const ext = "jpg";
    const filePath = join(destDir, `${image.id}.${ext}`);
    await downloadTo(photo.src.large2x, filePath);

    manifest[destination.slug][image.id] = {
      src: `/images/destinations/${destination.slug}/${image.id}.${ext}`,
      width: photo.width,
      height: photo.height,
      photographer: photo.photographer,
      photographerUrl: photo.photographer_url,
      pexelsUrl: photo.url,
    };

    console.log(`OK (${photo.photographer})`);
    await sleep(250);
  }
}

const outPath = join(rootDir, "src", "data", "destination-images.generated.ts");
const fileContents = `// AUTO-GENERATED by scripts/fetch-destination-images.mjs — do not edit by hand.
export type DestinationImageMeta = {
  src: string;
  width: number;
  height: number;
  photographer: string;
  photographerUrl: string;
  pexelsUrl: string;
};

export const destinationImages: Record<string, Record<string, DestinationImageMeta>> = ${JSON.stringify(manifest, null, 2)};
`;

writeFileSync(outPath, fileContents);
console.log(`\n[fetch-images] wrote ${outPath}`);
